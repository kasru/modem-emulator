#pragma once

#include <string_view>

namespace atmodem {

/**
 * @brief Проверяет полное соответствие текста шаблону ограниченного синтаксиса.
 *
 * Поддерживается упрощённый синтаксис (по условиям тестового задания):
 *   - @c `.`  — ровно один произвольный символ;
 *   - @c `*`  — ноль или больше любых символов (любое количество, т.е. аналог
 *     `.*` классических регулярных выражений);
 *   - @c `[abc]` — один символ из перечисленных; поддерживаются диапазоны
 *     вида `[a-z0-9]` и отрицание `[^0-9]`;
 *   - все остальные символы шаблона совпадают буквально.
 *
 * Сравнение выполняется без учёта регистра ASCII-букв (как у типичных
 * модемов: команда `ati` эквивалентна `ATI`).
 *
 * Соответствие всегда проверяется на ВСЮ строку целиком: текст считается
 * совпавшим с шаблоном только при полном покрытии от начала до конца.
 *
 * Реализация не использует стандартную библиотеку регулярных выражений:
 * применяется итеративный алгоритм классического сопоставления с маской,
 * где каждая `*` хранит единственную точку отката. В худшем случае текст
 * повторно просматривается до K раз, где K - число звёздочек в шаблоне,
 * т.е. сложность O(K * len(text)). При лимите строки в maxLineLength
 * байт (по умолчанию 128) и небольшом словаре это пренебрежимо мало.
 *
 * @param pattern Шаблон ограниченного синтаксиса.
 * @param text    Проверяемый текст (командная строка без терминатора CR).
 *
 * @return true, если весь текст соответствует шаблону; иначе false.
 *
 * @note Незакрытая скобка `[` считается обычным литеральным символом,
 *       чтобы некорректный шаблон не приводил к падению программы.
 */
[[nodiscard]] bool patternMatches(std::string_view pattern,
                                  std::string_view text) noexcept;

} // namespace atmodem
