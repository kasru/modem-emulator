#pragma once

#include <cstddef>
#include <string>
#include <string_view>

namespace atmodem {

/**
 * @brief Результат обработки одного входного символа модемом.
 */
struct FeedResult {
    bool echo = false;          ///< true, если нужно вернуть эхо-последовательность клиенту.
    std::string_view echoSeq;   ///< Эхо-последовательность (валидна до следующего feed()).
    bool lineCompleted = false; ///< true, если принят терминатор CR и строка готова.
    bool overflowed = false;    ///< true, если строка превысила лимит длины.
};

/**
 * @brief Посимвольный сборщик командной строки с редактированием, как у типичного
 *        модема (ITU-T V.250).
 *
 * Поведение:
 *   - `CR` (`\r`) — терминатор команды: строка считается завершённой;
 *   - `LF` (`\n`) игнорируется (прозрачно для клиентов, присылающих CRLF);
 *   - `NUL` (`\0`) игнорируется;
 *   - `BS` (`\b`, 0x08) и `DEL` (0x7F) стирают последний символ строки
 *     (эхо: `\b \b`);
 *   - `CAN` (0x18) и `NAK` (0x15) отменяют текущую строку целиком
 *     (буфер очищается; NAK поддержан, поскольку его шлют некоторые
 *     терминалы вместо CAN);
 *   - прочие печатные символы добавляются в буфер; при переполнении
 *     @p maxLineLength лишние символы отбрасываются и выставляется флаг
 *     overflow — завершённая такая строка должна получить ответ ERROR;
 *   - пустая строка (сразу CR) тоже считается завершённой: сервер её молча
 *     игнорирует, как это делают многие реальные модемы.
 *
 * Класс не выполняет ввод-вывод и потому тривиально тестируется.
 */
class LineAssembler {
public:
    /**
     * @brief Создаёт сборщик строк.
     *
     * @param maxLineLength Максимальная длина командной строки в символах.
     */
    explicit LineAssembler(std::size_t maxLineLength = 128) noexcept;

    /**
     * @brief Обрабатывает очередной входной символ.
     *
     * @param c Входной байт от клиента.
     *
     * @return Описание того, что сервер должен сделать (эхо, ответ...).
     */
    [[nodiscard]] FeedResult feed(char c);

    /**
     * @brief Забирает завершённую командную строку, если она есть.
     *
     * @param[out] out Сюда помещается текст строки без терминатора CR.
     *
     * @return true, если строка была извлечена; после вызова буфер очищен,
     *         включая признак переполнения.
     */
    bool takeLine(std::string& out);

    /**
     * @brief Полностью сбрасывает состояние: незавершённый буфер,
     *        признак переполнения и признак завершённости строки.
     *
     * Выделенная под буфер память сохраняется (ёмкость не уменьшается),
     * поэтому последующие строки не требуют новых аллокаций.
     */
    void reset();

    /**
     * @brief Текущее незавершённое содержимое буфера.
     *
     * @return Просмотр накопленных, но ещё не отправленных на обработку символов.
     */
    [[nodiscard]] std::string_view pending() const noexcept { return buffer_; }

    /**
     * @brief Была ли переполнена текущая (или последняя незабранная) строка.
     *
     * @return true, если длина строки превысила лимит.
     */
    [[nodiscard]] bool overflow() const noexcept { return overflow_; }

private:
    std::string buffer_;         ///< Накопитель текущей командной строки.
    std::size_t maxLineLength_;  ///< Предел длины командной строки.
    bool overflow_ = false;      ///< Признак переполнения текущей строки.
    bool completed_ = false;     ///< true, если получен терминатор CR.
    char echoChar_[1] = {0};     ///< Хранилище эха одиночного символа.

    /// Эхо-последовательность для стирания символа "\b \b".
    static constexpr std::string_view kEraseEcho = "\b \b";
    /// Эхо-последовательность отмены строки "\r\n".
    static constexpr std::string_view kCancelEcho = "\r\n";
};

} // namespace atmodem
